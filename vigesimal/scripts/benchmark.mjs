import { readFileSync, readdirSync, mkdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join, dirname } from 'node:path'
import { createHash } from 'node:crypto'
import { performance } from 'node:perf_hooks'
import { isDeepStrictEqual } from 'node:util'
import { encode, decode, analyze, inferSchema } from '../dist/index.mjs'
import { encode as toonEncode, decode as toonDecode } from '@toon-format/toon'
import { stringify as csvEncode } from 'csv-stringify/sync'
import { parse as csvDecode } from 'csv-parse/sync'
import { getEncoding } from 'js-tiktoken'

const root = fileURLToPath(new URL('../../', import.meta.url))
const tokenizer = getEncoding('o200k_base')
const count = value => tokenizer.encode(value, [], []).length
const hash = value => createHash('sha256').update(value).digest('hex')
const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'))
const results = []
for (const filename of readdirSync(join(root, 'benchmark/datasets')).filter(f => f.endsWith('.json')).sort()) {
  const source = readFileSync(join(root, 'benchmark/datasets', filename), 'utf8')
  const data = JSON.parse(source)
  let schema
  try { schema = inferSchema(filename.slice(0, -5), data) } catch {}
  const flat = !!schema && data.every(row => schema.fields.every(f => Object.hasOwn(row, f.name)))
  const encoders = [
    ['json_compact', () => JSON.stringify(data), JSON.parse],
    ['json_pretty', () => JSON.stringify(data, null, 2), JSON.parse],
    ['toon_official', () => toonEncode(data), toonDecode],
  ]
  if (flat) {
    encoders.push(['vigesimal_typed', () => encode(data, { name: filename.slice(0, -5), est: count }), decode])
    // CSV is a text table, not a self-describing JSON codec. Verify textual cell
    // fidelity only; do not imply that null and empty string retain JSON types.
    const fields = schema.fields.map(f => f.name)
    const cells = data.map(row => fields.map(f => row[f] == null ? '' : String(row[f])))
    encoders.push(['csv_rfc4180', () => csvEncode([fields, ...cells], { record_delimiter: '\r\n' }),
      text => ({ csvCells: csvDecode(text) }), { csvCells: [fields, ...cells] }])
  }
  for (const [encoder, render, parse, expected = data] of encoders) {
    render() // warm up
    const samples = []
    let output
    for (let i = 0; i < 5; i++) {
      const start = performance.now(); output = render(); samples.push(performance.now() - start)
    }
    if (!isDeepStrictEqual(parse(output), expected)) throw new Error(`${filename}/${encoder}: round-trip failed`)
    results.push({ dataset: filename.slice(0, -5), track: flat ? 'flat' : 'nested', encoder,
      tokens: count(output), bytes: Buffer.byteLength(output),
      medianEncodingMs: samples.sort((a, b) => a - b)[2],
      roundTrip: encoder.startsWith('csv') ? 'textual cells only' : 'JSON values',
      datasetSha256: hash(source), payloadSha256: hash(output) })
  }
  const selected = analyze(data, { est: count, tokenizer: 'o200k_base' })
  if (selected.outputTokens > selected.inputTokens) throw new Error('Fallback expanded payload')
}
const manifest = { generatedAt: new Date().toISOString(), kind: 'local-serialization-only',
  tokenizer: 'o200k_base', runtime: process.version, vigesimalVersion: pkg.version,
  dependencies: pkg.devDependencies,
  librarySha256: hash(readFileSync(new URL('../dist/index.mjs', import.meta.url))),
  harnessSha256: hash(readFileSync(fileURLToPath(import.meta.url))),
  modelCalls: 0, encodingSamples: 5,
  limitations: ['Synthetic datasets', 'No model quality, API billing, or end-to-end latency measured',
    'o200k_base counts are not Claude token counts', 'CSV checks textual cells, not typed JSON round-trips',
    'Nested inputs excluded from Vigesimal and CSV comparisons', 'Single-machine encoding timings are descriptive only'], results }
const path = join(root, 'benchmark/results/current-serialization.json')
mkdirSync(dirname(path), { recursive: true })
writeFileSync(path, JSON.stringify(manifest, null, 2) + '\n')
const markdown = ['# Current serialization benchmark', '',
  'Generated by `cd vigesimal && npm run benchmark`. No model calls or accuracy claims.', '',
  '| Dataset | Track | Encoder | o200k_base tokens | Median encode ms | Fidelity check |',
  '|---|---|---|---:|---:|---|',
  ...results.map(r => `| ${r.dataset} | ${r.track} | ${r.encoder} | ${r.tokens} | ${r.medianEncodingMs.toFixed(3)} | ${r.roundTrip} |`), '',
  '## Limitations', '', ...manifest.limitations.map(x => `- ${x}`), '',
  'Exact dependency versions and content hashes are in [the manifest](current-serialization.json).', ''].join('\n')
writeFileSync(path.replace('.json', '.md'), markdown)
console.log(markdown)
